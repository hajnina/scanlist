import java.util.Locale

// Unicode **full** case folding — RANK.md §3.1 (`norm(s) = NFC(s).casefold() ...`).
//
// The normative semantics are Python's `str.casefold()` (Unicode CaseFolding.txt, mappings C + S + F;
// the Turkic T mappings are excluded). Kotlin's `lowercase(Locale.ROOT)` is plain lowercasing, not
// case folding: it leaves `ß` as `ß` (fold `ss`), the ligature `ﬁ` as `ﬁ` (fold `fi`), the final
// sigma `ς` as `ς` (fold `σ`) and folds Cherokee down where case folding maps it up. Barcode matching
// is exact after normalisation, so those differences would make two tracks disagree on
// `BARCODE_MATCH` for the same product name.
//
// Implementation: per-code-point `lowercase(Locale.ROOT)` (the locale-independent default conversion,
// which already expands `İ` → `i` + U+0307 and `ẞ` → `ß`) followed by [FOLD_EXCEPTIONS], which maps
// every lowercased code point whose full fold differs to its folded string. Cherokee—the one script
// that folds "upward"—is handled arithmetically. [IDENTITY_OVERRIDES] pins code points whose full fold
// is the identity while newer engines' lowercase data maps them, so the result does not depend on the
// JVM/ICU Unicode version.
//
// Provenance: the table was generated by comparing Python 3.14.4 (`str.casefold()`, Unicode 16.0.0)
// against Temurin 17.0.21 `String.toLowerCase(Locale.ROOT)` for **all** 1,112,064 code points, and
// contains exactly the code points where the two differ (164 entries; 75 multi-code-point folds).
// The same exhaustive comparison is a unit test (`CaseFoldTest`), plus random-string fuzzing, so a
// JDK Unicode update that adds mappings is caught instead of silently changing `BARCODE_MATCH`.
// S8-sync's `shared/ts-core/src/casefold.ts` implements the same contract from CaseFolding.txt; its
// table is not on main yet (branch `card/S8-sync`), so this port was derived independently from the
// oracle. Cross-check that the two produce identical output once S8-sync merges.

