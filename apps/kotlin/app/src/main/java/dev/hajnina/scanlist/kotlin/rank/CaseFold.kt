/** Code points the engine lowercases but Python 3.14's Unicode 16 data folds to themselves. */
private val IDENTITY_OVERRIDES: Set<Int> = setOf(0xA7CE, 0xA7D2, 0xA7D4)

/** Cherokee folds *upward*: small syllabary U+AB70–U+ABBF and U+13F8–U+13FD → the capitals. */
private fun cherokeeFold(lowerFirst: Int): String? = when (lowerFirst) {
    in 0xAB70..0xABBF -> stringOf(0x13A0 + (lowerFirst - 0xAB70))
    in 0x13F8..0x13FD -> stringOf(0x13F0 + (lowerFirst - 0x13F8))
    else -> null
}

private fun stringOf(codePoint: Int): String = String(Character.toChars(codePoint))

/**
 * Unicode full case folding, equivalent to Python's `str.casefold()` (RANK.md §3.1).
 *
 * Iterates by code point so `İ` / `ẞ` / non-BMP Cyrillic are handled as single units; each is then
 * lowercased individually (never the whole string, which would apply context-sensitive final-sigma
 * rules) and folded through the exception table.
 */
internal fun fullCasefold(text: String): String {
    val out = StringBuilder(text.length)
    var index = 0
    while (index < text.length) {
        val codePoint = text.codePointAt(index)
        if (codePoint in IDENTITY_OVERRIDES || codePoint in 0x16EA0..0x16EB8) {
            out.appendCodePoint(codePoint)
        } else {
            val lower = stringOf(codePoint).lowercase(Locale.ROOT)
            val cherokee = cherokeeFold(lower.codePointAt(0))
            if (cherokee != null) out.append(cherokee) else out.append(FOLD_EXCEPTIONS[lower] ?: lower)
        }
        index += Character.charCount(codePoint)
    }
    return out.toString()
}
