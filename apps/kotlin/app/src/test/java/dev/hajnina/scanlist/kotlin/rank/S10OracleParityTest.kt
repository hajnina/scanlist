package dev.hajnina.scanlist.kotlin.rank

import kotlinx.serialization.json.Json
import kotlinx.serialization.json.JsonNull
import kotlinx.serialization.json.JsonObject
import kotlinx.serialization.json.doubleOrNull
import kotlinx.serialization.json.int
import kotlinx.serialization.json.jsonArray
import kotlinx.serialization.json.jsonObject
import kotlinx.serialization.json.jsonPrimitive
import org.junit.Assert.assertEquals
import org.junit.Assert.assertTrue
import org.junit.Test

/**
 * Card B3-sync's oracle-parity gate: the Kotlin [rank]/[decideTop] must reproduce the updated
 * `shared/ref/scanlist_ref.py` **exactly** over all 58 golden queries × 2 ticks (116 rank-runs),
 * including `topId` null-ness, the full `entries` order, and every stored score.
 *
 * The expectation file `rank/s10_oracle_runs.json` is generated by the Python oracle, not by this
 * implementation. Its `_provenance` header records the generator script (kept next to it), the exact
 * command, the `scanlist_ref.py` blob SHA-1, the git commit, Python/Unicode versions and the
 * `golden.json` SHA-256. Regenerate it whenever the oracle or fixture changes.
 *
 * Ticks are driven with the same inputs the oracle used: tick 1 `prev = null`; tick 2 the tick-1
 * state/output; image queries pass the fixture's OFF `product` as `barcodeName` (which is what lets
 * `honey.jpg` confirm Honey), text queries pass `null`. This deliberately differs from
 * `GoldenRankTest`, which passes no barcode name at all and therefore can never highlight an image
 * winner (§6.3).
 */
class S10OracleParityTest {

    private val dump: JsonObject by lazy {
        Json.parseToJsonElement(resource("s10_oracle_runs.json")).jsonObject
    }

    @Test
    fun `expectation dump has oracle provenance`() {
        val provenance = dump["_provenance"]!!.jsonObject
        assertEquals(58, provenance["runs"]!!.jsonPrimitive.int)
        assertEquals("shared/ref/scanlist_ref.py", provenance["ref"]!!.jsonPrimitive.content)
        assertTrue(provenance["command"]!!.jsonPrimitive.content.contains("gen_s10_oracle.py"))
        assertEquals(40, provenance["refBlobSha1"]!!.jsonPrimitive.content.length)
        assertEquals(64, provenance["fixtureSha256"]!!.jsonPrimitive.content.length)
        assertEquals(58, dump["runs"]!!.jsonArray.size)
    }

    @Test
    fun `all 116 rank-runs match the oracle exactly`() {
        val failures = ArrayList<String>()
        var runs = 0
        var comparedEntries = 0

        for (runElement in dump["runs"]!!.jsonArray) {
            val run = runElement.jsonObject
            val queryId = run["id"]!!.jsonPrimitive.content
            val query = Golden.queries.firstOrNull { it.id == queryId }
                ?: error("$queryId is not a golden query")
            val items = Golden.rankItems(Golden.list(query.list))
            val queries = when (query.kind) {
                "text" -> RankQueries(text = listOf(query.vector))
                "image" -> RankQueries(image = listOf(query.vector))
                else -> error("unknown query kind ${query.kind}")
            }
            val barcodeName = if (run["barcodeName"] is JsonNull) null else run["barcodeName"]!!.jsonPrimitive.content

            var state: RankState? = null
            var previous: RankResult? = null
            for ((tickIndex, tickElement) in run["ticks"]!!.jsonArray.withIndex()) {
                val tick = tickElement.jsonObject
                val result = rank(
                    items = items,
                    queries = queries,
                    prev = state,
                    barcodeName = barcodeName,
                    previous = previous,
                )
                runs++

                val where = "$queryId tick ${tickIndex + 1}"
                val expectedTopId = tick["topId"].stringOrNull()
                if (result.topId != expectedTopId) {
                    failures += "$where: topId ${result.topId} != $expectedTopId"
                }

                val expectedEntries = tick["entries"]!!.jsonArray.map { it.jsonObject }
                if (result.entries.size != expectedEntries.size) {
                    failures += "$where: ${result.entries.size} entries != ${expectedEntries.size}"
                } else {
                    for (index in expectedEntries.indices) {
                        val want = expectedEntries[index]
                        val have = result.entries[index]
                        comparedEntries++
                        if (have.id != want["id"]!!.jsonPrimitive.content) {
                            failures += "$where entry $index: id ${have.id} != ${want["id"]!!.jsonPrimitive.content}"
                        }
                        if (have.raw != want["raw"].doubleOrNullOrNull()) {
                            failures += "$where ${have.id}: raw ${have.raw} != ${want["raw"].doubleOrNullOrNull()}"
                        }
                        if (have.smoothed != want["smoothed"].doubleOrNullOrNull()) {
                            failures += "$where ${have.id}: smoothed ${have.smoothed} != ${want["smoothed"].doubleOrNullOrNull()}"
                        }
                        if (have.done != (want["done"]?.jsonPrimitive?.content == "true")) {
                            failures += "$where ${have.id}: done ${have.done} != ${want["done"]}"
                        }
                    }
                }
                state = result.state
                previous = result
            }
        }

        assertEquals("rank-runs replayed", 116, runs)
        assertTrue("entries compared: $comparedEntries", comparedEntries >= 2_000)
        assertTrue("${failures.size} divergent\n${failures.take(40).joinToString("\n")}", failures.isEmpty())
    }

    private fun kotlinx.serialization.json.JsonElement?.stringOrNull(): String? =
        if (this == null || this is JsonNull) null else jsonPrimitive.content

    private fun kotlinx.serialization.json.JsonElement?.doubleOrNullOrNull(): Double? =
        if (this == null || this is JsonNull) null else jsonPrimitive.doubleOrNull

    private fun resource(name: String): String =
        checkNotNull(javaClass.getResourceAsStream("/rank/$name")) { "missing test resource /rank/$name" }
            .bufferedReader(Charsets.UTF_8).use { it.readText() }
}
