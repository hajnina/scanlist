#!/usr/bin/env python3
"""X1 — rank() latency for 200 items on the **Python oracle** (`shared/ref/scanlist_ref.py`, card S2).

The oracle is the normative reference every track is checked against, so timing it gives the
comparison a third, independent implementation (numpy matmul per tick vs ts-core's scalar loops vs
the Kotlin port's scalar loops). It is NOT a track: nothing ships it. It is reported as `oracle.json`
and labelled as such everywhere.

    python3 bench/scripts/make-fixture.mjs   # (node) writes bench/.cache/rank200.txt
    bench/.venv/bin/python bench/scripts/rank-oracle.py

Writes bench/results/fragments/rank-oracle.json. Needs numpy only (bench/.venv, see README).
"""
from __future__ import annotations

import json
import math
import os
import statistics
import sys
import time
from datetime import datetime, timezone
from pathlib import Path

BENCH = Path(__file__).resolve().parent.parent
REPO = BENCH.parent
sys.path.insert(0, str(REPO / "shared" / "ref"))

import scanlist_ref  # noqa: E402  (path set above)

ITERATIONS = int(os.environ.get("X1_ITERATIONS", "300"))
WARMUP = int(os.environ.get("X1_WARMUP", "50"))


def percentile(sorted_samples: list[float], p: float) -> float:
    """Nearest-rank percentile (index = ceil(p/100 * n) - 1), identical to the JS/Kotlin helpers."""
    idx = min(len(sorted_samples) - 1, math.ceil((p / 100) * len(sorted_samples)) - 1)
    return sorted_samples[idx]


def stats(samples: list[float]) -> dict:
    s = sorted(samples)
    return {
        "n": len(s),
        "min": s[0],
        "p50": percentile(s, 50),
        "p95": percentile(s, 95),
        "max": s[-1],
        "mean": statistics.fmean(s),
        "unit": "ms",
    }


def read_fixture() -> tuple[dict, list[dict], dict]:
    path = BENCH / ".cache" / "rank200.txt"
    if not path.is_file():
        raise SystemExit(f"missing {path} — run: node bench/scripts/make-fixture.mjs")
    lines = [ln for ln in path.read_text().splitlines() if ln]
    meta = dict(kv.split("=") for kv in lines[0].split()[1:] if "=" in kv)
    items: list[dict] = []
    text: list[list[float]] = []
    image: list[list[float]] = []
    for line in lines[1:]:
        parts = line.split("|")
        if parts[0] == "ITEM":
            _, item_id, order, done, name, aliases, vec = parts
            items.append(
                {
                    "id": item_id,
                    "name": name,
                    "amount": None,
                    "unit": None,
                    "note": None,
                    "aliases": [a for a in aliases.split(";") if a],
                    "done": done == "1",
                    "path": [f"Section {int(order) // 10 + 1}"],
                    "pathText": f"Section {int(order) // 10 + 1}",
                    "index": int(order) % 10,
                    "order": int(order),
                    "vec": [float(x) for x in vec.split(",")],
                }
            )
        elif parts[0] == "TEXT":
            text.append([float(x) for x in parts[1].split(",")])
        elif parts[0] == "IMAGE":
            image.append([float(x) for x in parts[1].split(",")])
    return meta, items, {"text": text, "image": image}


def main() -> None:
    meta, items, queries = read_fixture()

    t0 = time.perf_counter()
    first = scanlist_ref.rank(items, queries, None)
    cold_ms = (time.perf_counter() - t0) * 1000

    state = first["state"]
    for _ in range(WARMUP):
        state = scanlist_ref.rank(items, queries, state)["state"]

    rank_samples: list[float] = []
    decide_samples: list[float] = []
    for _ in range(ITERATIONS):
        t0 = time.perf_counter()
        out = scanlist_ref.rank(items, queries, state)
        rank_samples.append((time.perf_counter() - t0) * 1000)
        state = out["state"]
        # The hero-first `entries` order is already rank order; decide_top only re-reads it.
        candidates = [
            {
                "id": e["id"],
                "order": i,
                "raw": e["raw"] or 0.0,
                "smoothed": e["smoothed"] or 0.0,
                "done": False,
                "source": "text",
            }
            for i, e in enumerate(out["entries"])
            if not e["done"]
        ]
        t0 = time.perf_counter()
        scanlist_ref.decide_top(candidates, state["topId"])
        decide_samples.append((time.perf_counter() - t0) * 1000)

    payload = {
        "generatedAt": datetime.now(timezone.utc).isoformat(),
        "implementation": "shared/ref/scanlist_ref.py (Python, numpy matmul per tick)",
        "provenance": {
            "source": "shared/ref/scanlist_ref.py",
            "role": "normative oracle — the reference every track is checked against; ships in no app",
            "fixture": "bench/.cache/rank200.txt (generated by bench/scripts/make-fixture.mjs)",
            "runner": f"python {sys.version.split()[0]} + numpy {scanlist_ref.np.__version__}, linux/aarch64",
        },
        "environment": {
            "python": sys.version.split()[0],
            "numpy": scanlist_ref.np.__version__,
            "iterations": ITERATIONS,
            "warmup": WARMUP,
            "items": len(items),
            "dims": int(meta["dims"]),
        },
        "measurements": {
            "rank200": stats(rank_samples),
            "decideTop200": stats(decide_samples),
            "rank200.coldFirstTick": {"status": "measured", "ms": cold_ms},
        },
        # Cross-implementation sanity: ts-core / Kotlin / oracle must agree on the hero id for this
        # workload, otherwise the three latency numbers would not describe the same computation.
        "sanity": {
            "topId": state["topId"],
            "entries": len(out["entries"]),
            "top3": [
                {"id": e["id"], "smoothed": e["smoothed"]}
                for e in out["entries"]
                if not e["done"]
            ][:3],
        },
    }
    out_dir = BENCH / "results" / "fragments"
    out_dir.mkdir(parents=True, exist_ok=True)
    (out_dir / "rank-oracle.json").write_text(json.dumps(payload, indent=2) + "\n")

    s = payload["measurements"]["rank200"]
    d = payload["measurements"]["decideTop200"]
    print(
        f"oracle rank(200 items, 16 text + 1 image queries): p50 {s['p50']:.3f} ms, "
        f"p95 {s['p95']:.3f} ms (min {s['min']:.3f}, max {s['max']:.3f}, n={s['n']}); "
        f"decide_top p95 {d['p95']:.4f} ms"
    )
    print("-> bench/results/fragments/rank-oracle.json")


if __name__ == "__main__":
    main()
